import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const read=p=>readFile(new URL('../'+p,import.meta.url),'utf8');
const applied=await read('supabase/migrations/20261103193309_phase0_2_scoped_access.sql');
const helpers=await read('supabase/review-candidates/scoped-access-helpers.sql');
const reports=await read('supabase/review-candidates/scoped-public-reports.sql');
const generated=await read('supabase/review-candidates/phase0-2-scoped-access.sql');
const functions=[...applied.matchAll(/CREATE OR REPLACE FUNCTION (ayuzee_private\.rbac_\w+|public\.search_patient|public\.set_leaderboard_visibility)\([\s\S]*?\bAS \$\$([\s\S]*?)\$\$;/g)];
if(functions.length!==17)throw Error('Unexpected applied function count '+functions.length);
const values=functions.map(m=>`('${m[1].split('.')[0]}','${m[1].split('.')[1]}','${createHash('md5').update(m[2]).digest('hex')}')`).join(',\n');
const dropViews=s=>s.replace(/^CREATE OR REPLACE VIEW [\s\S]*?;\s*/gm,'');
const policies=[...generated.matchAll(/^CREATE POLICY (ayuzee_scope_(?:read|insert|update|delete)) ON public\.(\w+)[^;]+;/gm)];
if(policies.length!==68)throw Error('Unexpected supporting policy count '+policies.length);
const sql=`-- Phase 1 Auth lifecycle compatibility and deleted-account denial.
-- Supersedes helper/policy bodies only; preserves all view definitions and data.
-- Existing source migration remains immutable. Generated by build-auth-lifecycle.mjs.
BEGIN;
SET LOCAL lock_timeout='5s';
SET LOCAL statement_timeout='60s';
DO $drift$ DECLARE expected record; actual text; matches integer; BEGIN
 IF NOT EXISTS(SELECT 1 FROM pg_attribute WHERE attrelid='auth.users'::regclass AND attname='deleted_at' AND atttypid='timestamptz'::regtype AND NOT attisdropped) THEN RAISE EXCEPTION 'Auth lifecycle contract changed'; END IF;
 FOR expected IN SELECT * FROM (VALUES ${values}) AS f(schema_name,function_name,fingerprint) LOOP
  SELECT min(md5(p.prosrc)),count(*) INTO actual,matches FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname=expected.schema_name AND p.proname=expected.function_name;
  IF matches<>1 OR actual IS DISTINCT FROM expected.fingerprint THEN RAISE EXCEPTION 'Function %.% changed since repair',expected.schema_name,expected.function_name; END IF;
 END LOOP;
END $drift$;
${dropViews(helpers)}
${dropViews(reports)}
DROP POLICY IF EXISTS ayuzee_active_account ON public.user_roles;
CREATE POLICY ayuzee_active_account ON public.user_roles AS RESTRICTIVE FOR SELECT TO authenticated USING(ayuzee_private.rbac_actor());
${policies.map(m=>`DROP POLICY IF EXISTS ${m[1]} ON public.${m[2]};\n${m[0]}`).join('\n')}
NOTIFY pgrst,'reload schema';
COMMIT;
`;
await writeFile(new URL('../supabase/review-candidates/phase1-auth-lifecycle.sql',import.meta.url),sql);
console.log('Generated Auth lifecycle upgrade with 17 function drift checks and 68 active-account policy fences.');
